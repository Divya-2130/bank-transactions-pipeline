"""Create the committed evidence in sample_output/ by running the pipeline on the small sample.

Run:  python -m src.make_sample_output

Three runs:
1. sample_run_1          normal run (allowed reject rate 60%, because the sample is 50% bad on purpose)
2. sample_run_2_rerun    the same file again into the same database (must add nothing)
3. sample_run_3_blocked  default 10% limit, so the quality gate fails and publish is blocked
"""
import csv
import json
import shutil
import sqlite3
import tempfile
from pathlib import Path

from src.db import connect
from src.orchestrator import Notifier, Orchestrator, default_specs
from src.tasks import RunContext

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "sample_output"
ACCOUNTS = ROOT / "data/sample/accounts.csv"
TXNS = ROOT / "data/sample/transactions.csv"
LABELS = ROOT / "data/sample_labels/expected_rejects.csv"


def run(db_path, run_id, max_reject_rate):
    conn = connect(db_path)
    ctx = RunContext(conn=conn, run_id=run_id, accounts_path=ACCOUNTS,
                     transactions_path=TXNS, output_dir=OUT,
                     max_reject_rate=max_reject_rate)
    orchestrator = Orchestrator(default_specs(retries=1, timeout=60),
                                Notifier(OUT / "alerts.log"), retry_delay=0)
    result = orchestrator.run(ctx)
    return conn, result


def md_table(headers, rows):
    lines = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    for row in rows:
        lines.append("| " + " | ".join("" if v is None else str(v) for v in row) + " |")
    return "\n".join(lines)


def export_csv(conn, sql, path):
    cur = conn.execute(sql)
    with open(path, "w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f)
        writer.writerow([d[0] for d in cur.description])
        writer.writerows(cur.fetchall())


def status_section(title, conn):
    runs = conn.execute(
        "SELECT run_id, status, rows_in, rows_clean, rows_rejected, failure_reason "
        "FROM pipeline_runs ORDER BY started_at, rowid").fetchall()
    out = [f"## {title}", "", md_table(
        ["run_id", "status", "rows_in", "rows_clean", "rows_rejected", "failure_reason"],
        [(r[0], r[1], r[2], r[3], r[4], (r[5] or "")[:120]) for r in runs]), ""]
    for (run_id,) in conn.execute("SELECT run_id FROM pipeline_runs ORDER BY started_at, rowid"):
        tasks = conn.execute(
            "SELECT task_name, status, attempts, COALESCE(error_message, '') FROM task_runs "
            "WHERE run_id = ? ORDER BY id", (run_id,)).fetchall()
        out += [f"### Tasks for {run_id}", "",
                md_table(["task", "status", "attempts", "error"],
                         [(t[0], t[1], t[2], t[3][:120]) for t in tasks]), ""]
    return out


def main():
    OUT.mkdir(exist_ok=True)
    for old in OUT.iterdir():
        if old.is_file():
            old.unlink()

    work = Path(tempfile.mkdtemp(prefix="bank_sample_"))
    conns = []
    try:
        conn1, res1 = run(work / "main.db", "sample_run_1", 0.60)
        conn2, res2 = run(work / "main.db", "sample_run_2_rerun", 0.60)  # same database
        conn3, res3 = run(work / "blocked.db", "sample_run_3_blocked", 0.10)
        conns = [conn1, conn2, conn3]
        main_db = conn2  # the same database after both runs

        # ---------------- exported tables
        export_csv(main_db, "SELECT * FROM clean_transactions ORDER BY transaction_id",
                   OUT / "clean_transactions.csv")
        export_csv(main_db, "SELECT record_type, source_file, row_number, record_key, "
                            "reject_reason, raw_record, run_id FROM rejected_records "
                            "ORDER BY record_type, row_number", OUT / "rejected_records.csv")
        export_csv(main_db, "SELECT * FROM daily_account_summary ORDER BY account_id, txn_date",
                   OUT / "daily_account_summary.csv")

        # ---------------- run status
        status = ["# Run status", "",
                  "Generated by `python -m src.make_sample_output`.", ""]
        status += status_section("Normal run, then a rerun of the same file (same database)", main_db)
        status += status_section("Blocked run (quality gate fails, nothing published)", conn3)
        (OUT / "run_status.md").write_text("\n".join(status), encoding="utf-8")

        # ---------------- sample queries and validation
        q = main_db.execute
        clean = q("SELECT COUNT(*) FROM clean_transactions").fetchone()[0]
        rejected = q("SELECT COUNT(*) FROM rejected_records WHERE record_type = 'transaction'").fetchone()[0]
        with open(TXNS, newline="", encoding="utf-8") as f:
            source_rows = sum(1 for _ in csv.DictReader(f))
        dup_ids = q("SELECT COUNT(*) FROM (SELECT transaction_id FROM clean_transactions "
                    "GROUP BY transaction_id HAVING COUNT(*) > 1)").fetchone()[0]
        orphans = q("SELECT COUNT(*) FROM clean_transactions c LEFT JOIN accounts a "
                    "ON c.account_id = a.account_id WHERE a.account_id IS NULL").fetchone()[0]
        on_closed = q("SELECT COUNT(*) FROM clean_transactions c JOIN accounts a "
                      "ON c.account_id = a.account_id WHERE a.status = 'closed'").fetchone()[0]
        net_summary = q("SELECT ROUND(SUM(net_amount), 2) FROM daily_account_summary").fetchone()[0]
        net_txn = q("SELECT ROUND(SUM(CASE WHEN txn_type = 'credit' THEN amount ELSE -amount END), 2) "
                    "FROM clean_transactions").fetchone()[0]

        with open(LABELS, newline="", encoding="utf-8") as f:
            expected = {int(r["row_number"]): r["expected_reject_reason"] for r in csv.DictReader(f)}
        actual = dict(q("SELECT row_number, reject_reason FROM rejected_records "
                        "WHERE record_type = 'transaction' AND source_file = 'transactions.csv'"))
        labels_ok = expected == actual

        ok = lambda cond: "PASS" if cond else "FAIL"
        checks = [
            ("source rows = clean + rejected", f"{source_rows} = {clean} + {rejected}", ok(source_rows == clean + rejected)),
            ("no duplicate transaction_id in target", f"{dup_ids} duplicates", ok(dup_ids == 0)),
            ("every transaction has a valid account (referential integrity)", f"{orphans} orphans", ok(orphans == 0)),
            ("no published transaction on a closed account", f"{on_closed} found", ok(on_closed == 0)),
            ("daily summary net = transaction net", f"{net_summary} vs {net_txn}", ok(net_summary == net_txn)),
            ("rerun added no new rows", f"rows_inserted_new = {res2['metrics'].get('rows_inserted_new')}", ok(res2["metrics"].get("rows_inserted_new") == 0)),
            ("rejects match the answer key exactly", f"{len(actual)} found vs {len(expected)} expected", ok(labels_ok)),
            ("blocked run published nothing", f"{conn3.execute('SELECT COUNT(*) FROM clean_transactions').fetchone()[0]} rows", ok(conn3.execute('SELECT COUNT(*) FROM clean_transactions').fetchone()[0] == 0)),
        ]

        queries = ["# Sample queries and validation", "",
                   "Generated by `python -m src.make_sample_output` from `data/sample/`.", "",
                   "## Validation checks", "", md_table(["check", "result", "status"], checks), "",
                   "## Rejects by reason", "",
                   md_table(["reject_reason", "count"], q(
                       "SELECT reject_reason, COUNT(*) FROM rejected_records "
                       "WHERE record_type = 'transaction' GROUP BY reject_reason ORDER BY 2 DESC, 1").fetchall()), "",
                   "## Top 5 accounts by net amount", "",
                   md_table(["account_id", "customer_name", "net_amount"], q(
                       "SELECT s.account_id, a.customer_name, ROUND(SUM(s.net_amount), 2) AS net "
                       "FROM daily_account_summary s JOIN accounts a ON a.account_id = s.account_id "
                       "GROUP BY s.account_id ORDER BY net DESC LIMIT 5").fetchall()), "",
                   "## Daily totals (first 10 rows)", "",
                   md_table(["account_id", "txn_date", "credits", "debits", "net", "count"], q(
                       "SELECT account_id, txn_date, total_credits, total_debits, net_amount, txn_count "
                       "FROM daily_account_summary ORDER BY txn_date, account_id LIMIT 10").fetchall()), "",
                   "## Account status history", "",
                   md_table(["account_id", "status", "effective_at"], q(
                       "SELECT account_id, status, effective_at FROM account_status_history "
                       "ORDER BY account_id LIMIT 10").fetchall()), ""]
        (OUT / "sample_queries.md").write_text("\n".join(queries), encoding="utf-8")

        print(md_table(["check", "result", "status"], checks))
        print("\nrun 1:", res1["status"], "| rerun:", res2["status"], "| blocked run:", res3["status"])
        print(f"Saved to {OUT}")
    finally:
        for c in conns:
            c.close()
        shutil.rmtree(work, ignore_errors=True)


if __name__ == "__main__":
    main()
